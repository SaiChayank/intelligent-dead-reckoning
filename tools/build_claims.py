import re  # noqa: E402

BLOCK_RE = re.compile(r"(<!-- CLAIMS:(\w+):BEGIN -->)(.*?)(<!-- CLAIMS:\2:END -->)", re.S)
VALUE_RE = re.compile(r"(<!--CV:(\w+)-->)(.*?)(<!--/CV-->)", re.S)
