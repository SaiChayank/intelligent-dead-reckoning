"""Build the results tables quoted in the README from generated result files only.

    python tools/build_claims.py            # writes reports/claims.md and refreshes README.md
    python tools/build_claims.py --check    # fails if either is out of date (used by tests)

Sources (each section is omitted, with a note, when its file is missing; nothing is typed in here):
  reports/iovnbd_eval/{vehicle,phone}/summary.json   IO-VNBD GNSS-outage evaluation
  reports/speed_v3_eval.json                         speed model v3, leave-one-drive-out
  reports/gnss_trust_eval.json                       learned GNSS trust study
  reports/synthetic_outage_measured.json             scripted synthetic drive, measured by the JVM test
  reports/map_matching_eval.json                     map matching on real Hyderabad road geometry (JVM test)

The README block between the CLAIMS markers is replaced; everything else in the README is hand-written.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / "reports"
README = ROOT / "README.md"
BEGIN, END = "<!-- CLAIMS:BEGIN (generated by tools/build_claims.py, do not edit) -->", "<!-- CLAIMS:END -->"

ARM_LABELS = {
    "ins": "INS only (no constraints)", "ekf_nhc": "EKF + NHC/ZUPT", "ekf_nhc_ai": "EKF + NHC/ZUPT + Model A v1",
    "ekf_nhc_v3": "EKF + NHC/ZUPT + speed correction v3 (in-sample weights)",
    "ekf_nhc_v3_heldout": "EKF + NHC/ZUPT + speed correction v3 (held-out weights)",
    "ekf_nhc_vel": "EKF + NHC/ZUPT + tight GNSS velocity (0.2 m/s)",
    "ekf_nhc_v3_heldout_vel": "EKF + NHC/ZUPT + v3 (held-out) + tight GNSS velocity",
    "ekf_nhc_v3_heldout_vel_nhcout": "EKF + NHC through outages + v3 (held-out) + tight GNSS velocity", "app": "App configuration",
    "hold_gnss": "Baseline: hold last GNSS velocity",
}
SCENARIO_LABELS = {"d50": "50 m outage", "t30": "30 s outage", "t60": "60 s outage", "d1000": "1 km outage"}


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def iovnbd_table(name: str, title: str) -> list[str]:
    s = load(REPORTS / "iovnbd_eval" / name / "summary.json")
    if s is None:
        return [f"_{title}: not generated (run tools/iovnbd_outage_eval.py)._", ""]
    drives = [d for d in s["drives"] if d["batch_calibration"] == "valid"]
    hours = sum(d["duration_s"] for d in drives) / 3600
    km = sum(d["distance_km"] for d in drives)
    lines = [f"**{title}** ({len(drives)} IO-VNBD drives, {hours:.1f} h, {km:.0f} km). "
             f"Median drift as a percentage of distance travelled in the outage, and the share of outages "
             f"under the 10 % gate. GNSS-aided error while fixes are available: "
             + ", ".join(f"{ARM_LABELS[a]} {v['median_m']} m median" for a, v in s["gnss_aided_accuracy"].items()
                         if a in ("ekf_nhc", "app")) + ".", "",
             "| Arm | " + " | ".join(SCENARIO_LABELS[k] for k in SCENARIO_LABELS if k in s["scenarios"]) + " |",
             "|---|" + "---:|" * len([k for k in SCENARIO_LABELS if k in s["scenarios"]])]
    for arm in ARM_LABELS:
        row = []
        for k in SCENARIO_LABELS:
            if k not in s["scenarios"]:
                continue
            v = s["scenarios"][k].get(arm)
            row.append("n/a" if not v or not v.get("scored") else
                       f"{v['drift_pct_median']:.0f} % ({v['pass_rate_drift_lt_10pct']:.0%})")
        if any(c != "n/a" for c in row):
            lines.append(f"| {ARM_LABELS[arm]} | " + " | ".join(row) + " |")
    if name == "vehicle" and "ekf_nhc_v3_heldout" in s["scenarios"].get("t30", {}):
        lines += ["", "_The in-sample v3 row uses weights trained on these same drives (optimistic). The held-out row "
                      "retrains without the drive being run, so it is the one to quote._"]
    elif name == "vehicle" and "ekf_nhc_v3" in s["engine_restarts_after_failure"]:
        lines += ["", "_The v3 row uses weights trained on these same drives (in-sample, optimistic)._"]
    return lines + [""]


def speed_v3_section() -> list[str]:
    s = load(REPORTS / "speed_v3_eval.json")
    if s is None:
        return ["_Speed model v3: not generated (run training/speed_v3.py evaluate)._", ""]
    r, d, p = s["speed_rmse"], s["drift_pct_median"], s["drift_pct_pass10"]
    return ["**Speed model v3** (learned correction of integrated acceleration, vehicle-frame inertial input, "
            f"leave-one-drive-out over {len(s['drives'])} drives):", "",
            "| | Hold last speed | Integrated acceleration | Learned v3 |", "|---|---:|---:|---:|",
            f"| Speed RMSE, all horizons (m/s) | {r['hold']['all']} | {r['integrated']['all']} | {r['learned']['all']} |",
            f"| Median drift over 30 s outages (%) | {d['h30_hold']} | {d['h30_integrated']} | {d['h30_learned']} |",
            f"| Median drift over 60 s outages (%) | {d['h60_hold']} | {d['h60_integrated']} | {d['h60_learned']} |",
            f"| Outages under 10 % drift, 30 s | {p['h30_hold']:.0%} | {p['h30_integrated']:.0%} | {p['h30_learned']:.0%} |",
            f"| Outages under 10 % drift, 60 s | {p['h60_hold']:.0%} | {p['h60_integrated']:.0%} | {p['h60_learned']:.0%} |",
            ""]


def synthetic_section() -> list[str]:
    s = load(REPORTS / "synthetic_outage_measured.json")
    if s is None:
        return ["_Scripted synthetic drive: no measured file (reports/synthetic_outage_measured.json)._", ""]
    lines = [f"**Scripted synthetic drive** ({s['description']}). Measured by the JVM test "
             f"`{s['produced_by']}`; this is a straight cruise, so it says little about real roads.", "",
             "| Arm | End error (m) | Drift (%) | Max error (m) |", "|---|---:|---:|---:|"]
    for a in s["arms"]:
        lines.append(f"| {a['label']} | {a['end_error_m']:.2f} | {a['drift_pct']:.2f} | {a['max_error_m']:.2f} |")
    return lines + [""]


def map_matching_section() -> list[str]:
    s = load(REPORTS / "map_matching_eval.json")
    if s is None:
        return ["_Map matching: no measured file (reports/map_matching_eval.json)._", ""]
    conditions = sorted({a["condition"] for a in s["arms"]})
    lines = [f"**Map matching on real Hyderabad road geometry** ({len(s['routes'])} routes from the shipped OSM graph). "
             f"{s['description']}. Median drift as a percentage of outage distance (share of outages under 10 %); "
             "`lane6m` puts the true lane 6 m from the mapped centreline.", "",
             "| Arm | " + " | ".join(f"{c}: 30 s | {c}: 60 s" for c in conditions) + " |",
             "|---|" + "---:|---:|" * len(conditions)]
    labels = {}
    for a in s["arms"]:
        labels.setdefault(a["arm_id"], a["label"])
    for arm_id, label in labels.items():
        cells = []
        for c in conditions:
            a = next(x for x in s["arms"] if x["arm_id"] == arm_id and x["condition"] == c)
            cells += [f"{a['drift_pct_median_30s']:.1f} % ({a['share_under_10pct_30s']:.0%})",
                      f"{a['drift_pct_median_60s']:.1f} % ({a['share_under_10pct_60s']:.0%})"]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    return lines + ["", "_Synthetic motion at constant speed along real road geometry, not a recorded drive._", ""]


def gnss_trust_section() -> list[str]:
    s = load(REPORTS / "gnss_trust_eval.json")
    if s is None:
        return []
    return ["**Learned GNSS trust** (research artifact, not in the engine; leave-one-drive-out, "
            f"{s['fixes']} phone fixes): rank correlation with true fix error {s['spearman']['learned']} "
            f"(reported accuracy: {s['spearman']['reported_accuracy']}); mean absolute error "
            f"{s['mae_m']['learned']} m (reported accuracy: {s['mae_m']['reported_accuracy']} m).", ""]


def build() -> str:
    parts = ["# Results, generated from result files", "",
             "Every number here is read from a file in `reports/` by `tools/build_claims.py`. Nothing is on a "
             "device or in a vehicle yet. IO-VNBD GNSS is the VBOX receiver at 1 Hz (the phone logged GPS only "
             "about every 9 s).", ""]
    parts += iovnbd_table("vehicle", "IO-VNBD, vehicle-frame inertial input (external-IMU case)")
    parts += iovnbd_table("phone", "IO-VNBD, phone IMU export")
    parts += speed_v3_section() + map_matching_section() + gnss_trust_section() + synthetic_section()
    return "\n".join(parts).rstrip() + "\n"


def refreshed_readme(claims: str) -> str:
    text = README.read_text(encoding="utf-8")
    body = claims.split("\n", 2)[2] if claims.startswith("# ") else claims
    block = f"{BEGIN}\n{body.rstrip()}\n{END}"
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        return head + block + tail
    return text


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--check", action="store_true")
    args = p.parse_args(argv)
    if not args.check:
        for built, record in (("map_matching_measured.json", "map_matching_eval.json"),):
            source = ROOT / "mobile" / "app" / "build" / built
            if source.is_file():
                (REPORTS / record).write_bytes(source.read_bytes())
    claims = build()
    readme = refreshed_readme(claims)
    claims_path = REPORTS / "claims.md"
    if args.check:
        ok = claims_path.is_file() and claims_path.read_text(encoding="utf-8") == claims and \
            README.read_text(encoding="utf-8") == readme
        print("claims up to date" if ok else "claims out of date: run tools/build_claims.py")
        return 0 if ok else 1
    claims_path.write_text(claims, encoding="utf-8", newline="\n")
    README.write_text(readme, encoding="utf-8", newline="\n")
    print(f"wrote {claims_path.relative_to(ROOT)} and refreshed README.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
